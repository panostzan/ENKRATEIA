import {createRequire} from 'node:module';
import {mkdtemp, mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const extension=path.join(root,'extension');
const profile=await mkdtemp(path.join(tmpdir(),'enkrateia-test-'));
await mkdir(path.join(root,'test-results'),{recursive:true});
const context=await chromium.launchPersistentContext(profile,{channel:'chromium',headless:true,args:['--disable-gpu',`--disable-extensions-except=${extension}`,`--load-extension=${extension}`],viewport:{width:1280,height:900}});
await context.route('https://enkrateia.test/**',route=>{
 const name=new URL(route.request().url()).pathname.slice(1);
 const title={research:'Research notes',draft:'Working draft',distraction:'Distraction'}[name];
 return route.fulfill({contentType:'text/html',body:'<title>'+title+'</title><h1>'+title+'</h1><input value="preserve me">'});
});
const pageErrors=[];context.on('page',page=>page.on('pageerror',e=>pageErrors.push(e.message)));
try {
 const worker=context.serviceWorkers()[0]||await context.waitForEvent('serviceworker');
 const base=worker.url().replace('/background.js','');
 const control=await context.newPage();await control.goto(base+'/popup.html');
 const send=(type,data={})=>control.evaluate(async({type,data})=>await chrome.runtime.sendMessage({type,...data}),{type,data});
 const first=await context.newPage();await first.goto('https://enkrateia.test/research');
 const second=await context.newPage();await second.goto('https://enkrateia.test/draft');
 let tabs=await worker.evaluate(()=>chrome.tabs.query({}));
 const firstId=tabs.find(t=>t.title==='Research notes').id,secondId=tabs.find(t=>t.title==='Working draft').id;
 const activate=id=>worker.evaluate(id=>chrome.tabs.update(id,{active:true}),id);
 const waitFor=async predicate=>{for(let i=0;i<100;i++){const s=await send('get');if(predicate(s))return s;await new Promise(r=>setTimeout(r,100));}throw Error('State timeout');};
 await control.bringToFront();await control.reload();if(process.env.SCREENSHOTS||process.argv.includes('--screenshots'))await control.screenshot({path:path.join(root,'test-results','popup.png'),timeout:10000,animations:'disabled',fullPage:true}); console.log('Popup loaded');
 await control.locator('input[value="' + firstId + '"]').check();await control.locator('input[value="' + secondId + '"]').check();await control.locator('#start').click();let result;
 await waitFor(s=>s.active?.mode==='focus');
 await new Promise(r=>setTimeout(r,400));await activate(secondId);
 await waitFor(s=>s.active?.lastProductive===secondId);assert.equal((await send('get')).active.attempts.length,0);
 const distraction=await context.newPage();await distraction.goto('https://enkrateia.test/distraction');
 let state=await waitFor(s=>s.active?.pending);let pending=state.active.pending;
 let gate=context.pages().find(p=>p.url()===base+'/gate.html')||await context.waitForEvent('page');
 await gate.waitForURL(base+'/gate.html');await gate.locator('#stay').waitFor();
 assert.equal(await gate.locator('#continue').isDisabled(),true);await distraction.locator('[data-enkrateia-shield]').waitFor({state:'attached'});
 result=await send('choice',{id:pending.id,choice:'continue'});assert.match(result.error,/eight/);
 if(process.env.SCREENSHOTS||process.argv.includes('--screenshots'))await gate.screenshot({path:path.join(root,'test-results','interruption.png'),timeout:10000,animations:'disabled',fullPage:true}); console.log('Interruption loaded');
 await gate.locator('#stay').click();await waitFor(s=>s.active?.mode==='focus');
 state=await send('get');assert.equal(state.active.attempts[0].choice,'stay');
 const distractionId=(await worker.evaluate(()=>chrome.tabs.query({}))).find(t=>t.title==='Distraction').id;
 await activate(distractionId);state=await waitFor(s=>s.active?.pending);pending=state.active.pending;
 gate=context.pages().find(p=>p.url()===base+'/gate.html')||await context.waitForEvent('page');await gate.waitForURL(base+'/gate.html');
 await gate.locator('#continue').waitFor();await new Promise(r=>setTimeout(r,8100));await gate.locator('#continue').click();
 state=await waitFor(s=>s.active?.mode==='distraction');assert.equal(state.active.attempts.length,2);
 assert.equal(await distraction.locator('input').inputValue(),'preserve me');assert.equal(await distraction.locator('[data-enkrateia-shield]').count(),0);
 await new Promise(r=>setTimeout(r,300));await activate(firstId);await waitFor(s=>s.active?.mode==='focus');
 await second.close();state=await waitFor(s=>s.active?.approved.length===1);assert.deepEqual(state.active.approved,[firstId]);
 await send('end');state=await send('get');assert.equal(state.active,null);assert.equal(state.history.length,1);
 const saved=state.history[0];assert.equal(saved.attempts.length,2);assert.ok(saved.segments.some(x=>x.kind==='focus'));assert.ok(saved.segments.some(x=>x.kind==='distraction'));
 const summary=context.pages().find(p=>p.url().includes('/summary.html'))||await context.waitForEvent('page');
 await summary.waitForURL('**/summary.html?*');await summary.locator('#report').waitFor();assert.equal(await summary.locator('#resistance').textContent(),'50%');
 if(process.env.SCREENSHOTS||process.argv.includes('--screenshots'))await summary.screenshot({path:path.join(root,'test-results','summary.png'),timeout:10000,animations:'disabled',fullPage:true}); console.log('Summary loaded');
 await send('start',{ids:[firstId]});await waitFor(s=>s.active?.mode==='focus');await first.close();
 state=await waitFor(s=>!s.active);assert.equal(state.history[0].endReason,'approved-tabs-closed');
 assert.deepEqual(pageErrors,[]);
 console.log('PASS: approved switching, new tabs, early Continue rejection, Stay, eight-second Continue, destination preservation, return, tab closure, summary and persistence.');
}finally {await context.close();}
